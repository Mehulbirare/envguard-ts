import { createEnv, generateExample, validateEnvFile } from '../src/core'
import { str, num, bool, url, port, email } from '../src/validators'
import { EnvValidationError } from '../src/errors'

// ---------------------------------------------------------------------------
// createEnv — happy paths
// ---------------------------------------------------------------------------
describe('createEnv() — valid input', () => {
  it('returns typed values from process.env substitute', () => {
    const env = createEnv({
      schema: {
        HOST: str(),
        PORT: port(),
        DEBUG: bool(),
      },
      env: { HOST: 'localhost', PORT: '4000', DEBUG: 'true' },
    })
    expect(env.HOST).toBe('localhost')
    expect(env.PORT).toBe(4000)
    expect(env.DEBUG).toBe(true)
  })

  it('uses defaults for missing optional variables', () => {
    const env = createEnv({
      schema: {
        PORT: port({ default: 3000 }),
        DEBUG: bool({ default: false }),
        TAG: str({ default: 'latest' }),
      },
      env: {},
    })
    expect(env.PORT).toBe(3000)
    expect(env.DEBUG).toBe(false)
    expect(env.TAG).toBe('latest')
  })

  it('returns a frozen object', () => {
    const env = createEnv({ schema: { X: str() }, env: { X: 'hello' } })
    expect(Object.isFrozen(env)).toBe(true)
  })

  it('treats empty string same as missing', () => {
    const env = createEnv({
      schema: { PORT: port({ default: 8080 }) },
      env: { PORT: '' },
    })
    expect(env.PORT).toBe(8080)
  })
})

// ---------------------------------------------------------------------------
// createEnv — error paths
// ---------------------------------------------------------------------------
describe('createEnv() — invalid input', () => {
  it('throws EnvValidationError when required variable is missing', () => {
    expect(() =>
      createEnv({ schema: { API_KEY: str() }, env: {} }),
    ).toThrow(EnvValidationError)
  })

  it('collects multiple errors in one throw', () => {
    try {
      createEnv({
        schema: {
          A: str(),
          B: num(),
          C: port(),
        },
        env: { B: 'not-a-number', C: '99999' },
      })
      fail('should have thrown')
    } catch (e) {
      expect(e).toBeInstanceOf(EnvValidationError)
      const err = e as EnvValidationError
      // A is missing, B is invalid, C is out of range
      expect(err.errors.length).toBe(3)
      expect(err.errors.map((x) => x.field)).toEqual(expect.arrayContaining(['A', 'B', 'C']))
    }
  })

  it('masks secret values in error output', () => {
    try {
      createEnv({
        schema: { TOKEN: str({ secret: true, minLength: 20 }) },
        env: { TOKEN: 'short' },
      })
    } catch (e) {
      const err = e as EnvValidationError
      expect(err.errors[0]?.received).toBe('[secret]')
    }
  })

  it('calls onError before throwing', () => {
    const onError = jest.fn()
    expect(() =>
      createEnv({
        schema: { X: str() },
        env: {},
        onError,
      }),
    ).toThrow(EnvValidationError)
    expect(onError).toHaveBeenCalledTimes(1)
    expect(onError.mock.calls[0]?.[0]).toHaveLength(1)
  })

  it('does not throw when skipValidation is true', () => {
    expect(() =>
      createEnv({
        schema: { X: str() },
        env: {},
        skipValidation: true,
      }),
    ).not.toThrow()
  })
})

